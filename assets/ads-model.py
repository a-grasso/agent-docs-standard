"""Generates ads-model.svg, the README's "model at a glance" diagram: python3 assets/ads-model.py"""

from pathlib import Path

MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace"
SANS = "-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif"
INK, MUTED, GUIDE = "#343a40", "#6c757d", "#ced4da"
IMM = ("#d0bfff", "#6741d9")
MUT = ("#f1f3f5", "#868e96")
DOCS = ("#ffc9c9", "#c92a2a")
MONO_CHAR_WIDTH = 7.4
W, H = 900, 690

out = []


def add(s):
    out.append(s)


def text(x, y, s, size=13, mono=True, bold=False, fill=INK, anchor="start", italic=False):
    weight = ' font-weight="600"' if bold else ""
    style = ' font-style="italic"' if italic else ""
    add(f'<text x="{x}" y="{y}" font-family="{MONO if mono else SANS}" font-size="{size}"{weight}{style}'
        f' fill="{fill}" text-anchor="{anchor}" dominant-baseline="central">{s}</text>')


def chip(x, y, label, colors, bold=False, h=22, size=12):
    w = round(len(label) * MONO_CHAR_WIDTH * size / 13 + 16)
    add(f'<rect x="{x}" y="{y - h / 2}" width="{w}" height="{h}" rx="5" fill="{colors[0]}" stroke="{colors[1]}"/>')
    text(x + w / 2, y + 0.5, label, size=size, bold=bold, anchor="middle")
    return x + w


def chips(x, y, items, gap=6):
    for label, colors in items:
        x = chip(x, y, label, colors) + gap
    return x


def arrow(d, dashed=False):
    dash = ' stroke-dasharray="5 4"' if dashed else ""
    add(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="1.4"{dash} marker-end="url(#arrow)"/>')


def guide(d):
    add(f'<path d="{d}" fill="none" stroke="{GUIDE}" stroke-width="1.4"/>')


add(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img">')
add("<!-- Generated by ads-model.py. Edit that, not this file. -->")
add("<title>ADS model: a project tree of AGENTS.md nodes linked by ref/up, "
    "with dep pointers off-repo and work state in the tracker</title>")
add('<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
    f'orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="{INK}"/></marker></defs>')
add(f'<rect width="{W}" height="{H}" rx="12" fill="#ffffff"/>')

text(92, 40, "my-project/", size=14, bold=True)
text(200, 40, "root: .git (monorepo) or local workdir (polyrepo)", size=12, mono=False, fill=MUTED)

modules = [
    ("api/", ("#b2f2bb", "#2b8a3e"), 135, [("adr/", IMM), ("references/", MUT)]),
    ("web/", ("#a5d8ff", "#1971c2"), 250, [("decisions/", IMM)]),
    ("worker/", ("#ffec99", "#e67700"), 365, [("adr/", IMM)]),
    ("infra/", ("#96f2d7", "#0c8599"), 480, [("runbooks/", MUT)]),
]
INDEX_Y = 85
ROOT_DOCS_Y = 595
BUS_X = 380

guide(f"M104,52 V{ROOT_DOCS_Y}")
for y in [INDEX_Y] + [m[2] for m in modules] + [ROOT_DOCS_Y]:
    guide(f"M104,{y} H118")

add(f'<rect x="120" y="{INDEX_Y - 16}" width="280" height="32" rx="6" fill="#e9ecef" stroke="{INK}" stroke-width="2"/>')
text(134, INDEX_Y + 0.5, "AGENTS.md", bold=True)
text(226, INDEX_Y + 0.5, "project index", size=12, mono=False, fill=MUTED)

for name, colors, y, docs in modules:
    agents_y, docs_y = y + 35, y + 70
    guide(f"M134,{y + 12} V{docs_y}")
    guide(f"M134,{agents_y} H148")
    guide(f"M134,{docs_y} H148")
    chip(120, y, name, colors, bold=True, h=24, size=13)
    add(f'<rect x="150" y="{agents_y - 14}" width="112" height="28" rx="6" fill="#ffffff" stroke="{INK}"/>')
    text(206, agents_y + 0.5, "AGENTS.md", anchor="middle")
    chips(chip(150, docs_y, "docs/", DOCS) + 8, docs_y, docs)
    arrow(f"M{BUS_X},{agents_y} H264")

arrow(f"M{BUS_X},{modules[-1][2] + 35} V{INDEX_Y + 18}")
text(BUS_X + 10, 132, "ref: ↓", size=12)
text(BUS_X + 10, 150, "up: ↑", size=12)

chips(chip(120, ROOT_DOCS_Y, "docs/", DOCS) + 8, ROOT_DOCS_Y,
      [("adr/", IMM), ("decisions/", IMM), ("records/", IMM), ("concept/", MUT), ("glossary.md", MUT)])

add('<rect x="600" y="28" width="282" height="190" rx="10" fill="#f8f9fa" stroke="#adb5bd" stroke-dasharray="5 4"/>')
text(616, 48, "off-repo", size=12, mono=False, bold=True)
text(672, 48, "not discoverable from the tree", size=12, mono=False, fill=MUTED)
for i, (name, kind) in enumerate([("design-system", "repo · AGENTS.md"),
                                  ("shared-config", "repo · AGENTS.md"),
                                  ("vendor API docs", "URL")]):
    cy = 82 + i * 46
    add(f'<rect x="618" y="{cy - 16}" width="248" height="32" rx="6" fill="#ffffff" stroke="#868e96"/>')
    text(632, cy + 0.5, name, bold=True)
    text(854, cy + 0.5, kind, size=11, mono=False, fill=MUTED, anchor="end")
    arrow(f"M400,{INDEX_Y - 5} C500,{INDEX_Y - 5} 510,{cy} 616,{cy}")
text(430, 68, "dep:", size=12)

add('<rect x="618" y="262" width="248" height="56" rx="6" fill="#ffffff" stroke="#868e96" stroke-dasharray="5 4"/>')
text(632, 282, "issue tracker", size=13, mono=False, bold=True)
text(632, 302, "status · sequencing · what's next", size=12, mono=False, fill=MUTED)
arrow(f"M400,{INDEX_Y + 9} C520,{INDEX_Y + 9} 500,290 616,290", dashed=True)
text(518, 190, "tracker:", size=12)
text(618, 336, "work state never enters the repo", size=12, mono=False, fill=MUTED, italic=True)

LEGEND_Y = 650
add(f'<path d="M24,{LEGEND_Y - 22} H{W - 24}" stroke="#e9ecef"/>')
x = 40
for colors, label in [(IMM, "immutable, dated"), (MUT, "mutable, time-neutral"), (DOCS, "docs/ folder")]:
    add(f'<rect x="{x}" y="{LEGEND_Y - 7}" width="14" height="14" rx="3" fill="{colors[0]}" stroke="{colors[1]}"/>')
    text(x + 22, LEGEND_Y + 0.5, label, size=12, mono=False, fill=MUTED)
    x += 22 + len(label) * 6.6 + 28
text(W - 40, LEGEND_Y + 0.5, "every AGENTS.md has a CLAUDE.md alias", size=12, mono=False, fill=MUTED, anchor="end")

add("</svg>")
Path(__file__).with_name("ads-model.svg").write_text("\n".join(out) + "\n")
